// FilePDF is the PDF of the pack, in the zip and beside it.
const FilePDF = "evidence-pack.pdf"

// pdfProducer is the fixed producer string, so two runs write the same bytes.
const pdfProducer = "ctfkit by compliance.tf"

// sectionTitles are the numbered parts of the pack, in pack.md's order.
var sectionTitles = []struct{ num, title string }{
	{"1", "Summary"},
	{"2", "Scope"},
	{"3", "What this pack shows, and what it does not"},
	{"4", "Control-to-clause mapping"},
	{"5", "Controls with no clause in a framework"},
	{"6", "Catalog controls not enforced by these modules"},
	{"7", "Enforcement tests"},
	{"A", "Clause register"},
}

// RenderPDF renders evidence-pack.pdf: an A4 document with a cover, a
// contents page, sections 1 to 7 and annex A. It lays the pack out twice:
// the first pass learns the page count and where each section starts, the
// second draws with them.
func RenderPDF(p *Pack) (File, error) {
	first, err := layoutPDF(p, 0, nil)
	if err != nil {
		return File{}, err
	}
	d, err := layoutPDF(p, first.page, first.sections)
	if err != nil {
		return File{}, err
	}
	created, err := time.Parse(time.RFC3339, p.GeneratedAt)
	if err != nil {
		created = zipTime
	}
	d.pdf.SetInfo(gopdf.PdfInfo{
		Title:        "Compliance evidence pack",
		Subject:      p.Release.Name,
		Creator:      p.Generator.Name + " " + p.Generator.Version,
		Producer:     pdfProducer,
		CreationDate: created.UTC(),
	})
	var buf bytes.Buffer
	if _, err := d.pdf.WriteTo(&buf); err != nil {
		return File{}, fmt.Errorf("evidence pack: pdf: %w", err)
	}
	return File{Name: FilePDF, Body: buf.Bytes()}, nil
}

// layoutPDF draws the whole pack. total and toc are zero on the first pass.
func layoutPDF(p *Pack, total int, toc map[string]int) (*pdfDoc, error) {
	d, err := newPDFDoc("Compliance evidence pack  "+orNotSet(p.Release.Name), total)
	if err != nil {
		return nil, err
	}
	names := map[string]string{}
	for _, fw := range p.Frameworks {
		names[fw.ID] = fw.Name
	}
	fwName := func(id string) string {
		if n := names[id]; n != "" {
			return n
		}
		return id
	}

	d.cover(p)
	d.contents(toc)
	d.summary(p, fwName)
	d.scope(p)
	d.shows(p)
	d.mapping(p, fwName)
	d.noClause(p, fwName)
	d.notEnforced(p)
	d.tests(p)
	d.register(p)
	return d, d.err
}

func (d *pdfDoc) cover(p *Pack) {
	d.newPage()
	img, err := gopdf.ImageHolderByBytes(logoPNG)
	d.fail(err)
	const logoH = 9.0
	d.fail(d.pdf.ImageByHolder(img, marginX, d.y, &gopdf.Rect{W: logoH * 1191 / 240, H: logoH}))
	by := "Generated by ctfkit by compliance.tf"
	d.put(pageW-marginX-d.width(bold, 8, by), d.y+logoH-lineHeight(8, 1), bold, 8, ink2, by)
	d.y += logoH + 4
	d.hline(marginX, marginX+contentW, d.y, rule3, ink)
	d.y += 16

	title := []run{{text: "Compliance evidence pack", face: bold, color: ink}}
	d.y += d.drawLines(d.wrap(title, 34, 120), marginX, d.y, 34, 1.08) + 4
	d.flow(pp(12, muted("Release "), strong(orNotSet(p.Release.Name))), marginX, contentW, 9)

	fws := []run{}
	for i, fw := range p.Frameworks {
		if i > 0 {
			fws = append(fws, txt(", "))
		}
		fws = append(fws, fwRun(fw.ID, fw.Name, sans))
	}
	if len(fws) == 0 {
		fws = []run{txt(none)}
	}
	commit := []run{txt(notSet)}
	if p.Release.Commit != "" {
		commit = []run{mon(p.Release.Commit)}
	}
	d.factTable([][2][]run{
		{{strong("Release")}, {txt(orNotSet(p.Release.Name))}},
		{{strong("Commit")}, commit},
		{{strong("Generated")}, {txt(fmt.Sprintf("%s by %s %s", orNotSet(p.GeneratedAt), orNotSet(p.Generator.Name), orNotSet(p.Generator.Version)))}},
		{{strong("Control catalog")}, append([]run{txt(orNotSet(p.Catalog.Version) + ", ")}, inline(catalogSource(p.Catalog), txt(""))...)},
		{{strong("Frameworks")}, fws},
	})
	d.y += 8

	// The status box: dashed, because the pack is open, not attested.
	body := pp(9, append([]run{txt("This pack records what ctfkit by compliance.tf read from the module manifests installed by ")},
		mon("terraform init"), txt(". compliance.tf does not sign, attest or verify it."))...)
	w := contentW - 10
	h := lineHeight(11, 1.3) + 1 + d.paraHeight(body, w) + 8
	d.stroke(ink)
	d.pdf.SetLineWidth(rule2)
	d.pdf.SetCustomLineType([]float64{1.5, 1}, 0)
	d.pdf.RectFromUpperLeftWithStyle(marginX, d.y, contentW, h, "D")
	d.pdf.SetLineType("solid")
	d.y += 4
	d.put(marginX+5, d.y, bold, 11, ink, Notice)
	d.y += lineHeight(11, 1.3) + 1
	d.y += d.drawLines(d.wrap(body.runs, 9, w), marginX+5, d.y, 9, 1.45) + 4
}

func (d *pdfDoc) factTable(rows [][2][]run) {
	t := table{widths: []float64{0.3, 0.7}, topRule: true}
	for _, r := range rows {
		t.rows = append(t.rows, []tcell{{pp(9, r[0]...)}, {pp(9, r[1]...)}})
	}
	d.drawTable(t, 0)
}

// chapter draws a section head and its lead, kept on one page with keep mm
// of what follows, and records the page the section starts on.
func (d *pdfDoc) chapter(num, title string, lead []run, keep float64, newPage bool) {
	head := pp(16, strong(title))
	head.leading = 1.15
	leadP := pp(sizeBody, lead...)
	w := contentW - 14
	h := 4 + d.paraHeight(head, w) + 3 + keep
	if lead != nil {
		h += d.paraHeight(leadP, w) + 4
	}
	if newPage {
		d.newPage()
	} else {
		d.y += 9
		d.ensure(h)
	}
	d.sections[num] = d.page
	d.hline(marginX, marginX+contentW, d.y, rule2, ink)
	d.y += 4
	d.put(marginX, d.y, bold, 20, ink, num)
	d.y += d.drawLines(d.wrap(head.runs, 16, w), marginX+14, d.y+0.8, 16, 1.15) + 3
	if lead != nil {
		d.y += d.drawLines(d.wrap(leadP.runs, sizeBody, w), marginX+14, d.y, sizeBody, 1.45) + 4
	}
}

// noneLine is the paragraph an empty section reads.
func (d *pdfDoc) noneLine() {
	d.flow(pp(sizeBody, txt(none+".")), marginX+14, contentW-14, 0)
}

func (d *pdfDoc) contents(toc map[string]int) {
	d.newPage()
	d.sections["contents"] = d.page
	d.hline(marginX, marginX+contentW, d.y, rule2, ink)
	d.y += 4
	d.put(marginX, d.y, bold, 20, ink, "Contents")
	d.y += 14
	t := table{widths: []float64{0.08, 0.8, 0.12}}
	for _, s := range sectionTitles {
		page := "0"
		if toc != nil {
			page = fmt.Sprint(toc[s.num])
		}
		t.rows = append(t.rows, []tcell{{pp(10, strong(s.num))}, {pp(10, txt(s.title))}, {pp(10, strong(page))}})
	}
	d.drawTable(t, 0)
}

func (d *pdfDoc) summary(p *Pack, fwName func(string) string) {
	s := p.Summary
	rows := [][2][]run{
		{{strong("Modules in scope")}, {txt(fmt.Sprintf("%d, %d with a compliance.tf manifest", s.Modules, s.ModulesWithManifest))}},
		{{strong("Controls enforced")}, {txt(fmt.Sprint(s.ControlsEnforced))}},
		{{strong("Controls delegated to another scope")}, {txt(fmt.Sprint(s.ControlsDelegated))}},
	}
	for _, fc := range s.PerFramework {
		rows = append(rows, [2][]run{
			{strong("With a "), fwRun(fc.Framework, fwName(fc.Framework), bold), strong(" clause")},
			{txt(fmt.Sprintf("%d of %d", fc.WithClause, fc.Of))},
		})
	}
	rows = append(rows,
		[2][]run{{strong("Framework gaps with a recorded reason")}, {txt(fmt.Sprintf("%d of %d", s.NoClauseWithReason, s.NoClause))}},
		[2][]run{{strong("Catalog controls for these resource types not enforced here")}, {txt(fmt.Sprint(s.NotEnforced))}},
		[2][]run{{strong("Control enforcement tests")}, {txt(testSummary(p.Tests))}},
		[2][]run{{strong("Findings at error level")}, {txt(count(s.FindingsAtError))}},
	)
	d.chapter("1", sectionTitles[0].title, []run{muted("Counts are taken from the module manifests and the control catalog named on the cover.")}, 12, true)
	d.factTable(rows)
}

func (d *pdfDoc) scope(p *Pack) {
	lead := inline("The modules `terraform init` installed for this release. A module without a compliance.tf manifest is listed in the report findings.", muted(""))
	if len(p.Scope) == 0 {
		d.chapter("2", sectionTitles[1].title, lead, 8, false)
		d.noneLine()
		return
	}
	t := table{widths: []float64{0.22, 0.36, 0.14, 0.28}, head: headCells("Module", "Source", "Version", "Manifest sha256")}
	for _, m := range p.Scope {
		sha := pp(sizeTable, mon(m.ManifestSHA256))
		switch {
		case m.ManifestSHA256 != "":
		case m.DeclaresNoResources:
			sha = pp(sizeTable, muted(none+", declares no resources"))
		default:
			sha = pp(sizeTable, muted(none))
		}
		t.rows = append(t.rows, []tcell{
			{pp(sizeTable, mon(orNotSet(m.Key)))}, {pp(sizeTable, mon(orNotSet(m.Source)))},
			{pp(sizeTable, txt(orNotSet(m.Version)))}, {sha},
		})
	}
	d.chapter("2", sectionTitles[1].title, lead, d.tableStart(t), false)
	d.drawTable(t, 0)
}

func headCells(titles ...string) []tcell {
	out := make([]tcell, len(titles))
	for i, t := range titles {
		out[i] = tcell{pp(8, strong(t))}
	}
	return out
}

// shows draws section 3: two boxes side by side, the second on mist.
func (d *pdfDoc) shows(p *Pack) {
	const gap, pad = 6.0, 5.0
	w := (contentW - gap) / 2
	inner := w - 2*pad
	listH := func(items []string) float64 {
		h := lineHeight(10.5, 1.3) + 2
		for _, it := range items {
			h += d.paraHeight(pp(sizeBody, txt(it)), inner-4) + 1.6
		}
		return h
	}
	h := max(listH(p.Shows), listH(p.DoesNotShow)) + 8
	d.chapter("3", sectionTitles[2].title, nil, h, false)
	top := d.y
	d.hline(marginX, marginX+w, top, rule2, ink)
	d.rect(marginX+w+gap, top, w, h, mist)
	box := func(x float64, title string, items []string) {
		y := top + 4
		d.put(x, y, bold, 10.5, ink, title)
		y += lineHeight(10.5, 1.3) + 2
		for _, it := range items {
			d.rect(x, y+1.6, 1.3, 1.3, violet)
			y += d.drawLines(d.wrap([]run{txt(it)}, sizeBody, inner-4), x+4, y, sizeBody, 1.45) + 1.6
		}
	}
	box(marginX, "It shows", p.Shows)
	box(marginX+w+gap+pad, "It does not show", p.DoesNotShow)
	d.y = top + h
}

func (d *pdfDoc) mapping(p *Pack, fwName func(string) string) {
	lead := []run{muted("Every control each module manifest lists, with the clauses it gives evidence for. Clause titles are in annex A.")}
	d.chapter("4", sectionTitles[3].title, lead, 20, true)
	if len(p.Mapping) == 0 {
		d.noneLine()
		return
	}
	for i, mm := range p.Mapping {
		n := len(mm.Frameworks)
		widths := []float64{0.4, 0.14}
		head := []tcell{{pp(8, strong("Control"))}, {pp(8, strong("Status"))}}
		for _, fw := range mm.Frameworks {
			widths = append(widths, 0.46/float64(max(n, 1)))
			head = append(head, tcell{pp(8, fwRun(fw, fwName(fw), bold))})
		}
		t := table{widths: widths, head: head}
		for _, mc := range mm.Controls {
			status := pp(sizeTable, muted(orNotSet(mc.Status)))
			if mc.Status == "enforced" {
				v := violet
				status = pp(sizeTable, run{text: mc.Status, face: bold, color: ink, mark: &v})
			}
			row := []tcell{{pp(sizeTable, mon(mc.ID)), pp(sizeTable, muted(orNotSet(mc.Name)))}, {status}}
			for _, fc := range mc.Clauses {
				row = append(row, tcell{pp(sizeTable, clauseRuns(fc.Clauses)...)})
			}
			t.rows = append(t.rows, row)
		}
		sub := pp(10.5, strong("Module "), mon(mm.Module))
		gapBefore := 2.0
		if i > 0 {
			gapBefore = 7
		}
		d.y += gapBefore
		d.ensure(d.paraHeight(sub, contentW) + 2 + d.tableStart(t))
		d.flow(sub, marginX, contentW, 2)
		d.drawTable(t, 2)
	}
	d.flow(pp(7.8, run{text: "CC7.3", face: mono, color: ink, dashed: true}, muted(" dashed: supporting clause, partial or indirect evidence.   "),
		muted("None "), strong("5"), muted(": no clause in that framework, reason in section 5.")), marginX, contentW, 0)
}

func clauseRuns(refs []ClauseRef) []run {
	if len(refs) == 0 {
		return []run{muted(none + " "), strong("5")}
	}
	out := make([]run, 0, len(refs))
	for i, r := range refs {
		text := orNotSet(r.ID)
		if i < len(refs)-1 {
			text += "  "
		}
		out = append(out, run{text: text, face: mono, color: ink, dashed: r.Supporting})
	}
	return out
}

func (d *pdfDoc) noClause(p *Pack, fwName func(string) string) {
	lead := []run{muted("A control can have no matching clause in a framework. The reason comes from the control catalog.")}
	if len(p.NoClause) == 0 {
		d.chapter("5", sectionTitles[4].title, lead, 8, false)
		d.noneLine()
		return
	}
	t := table{widths: []float64{0.36, 0.64}, head: headCells("Control", "Framework and reason")}
	for _, nc := range p.NoClause {
		reasons := tcell{}
		for _, f := range nc.Frameworks {
			reasons = append(reasons, pp(sizeTable, fwRun(f.Framework, fwName(f.Framework), bold), txt(": "+orNotSet(f.Reason))))
		}
		t.rows = append(t.rows, []tcell{{pp(sizeTable, mon(nc.ID)), pp(sizeTable, muted(orNotSet(nc.Name)))}, reasons})
	}
	d.chapter("5", sectionTitles[4].title, lead, d.tableStart(t), false)
	d.drawTable(t, 0)
}

func (d *pdfDoc) notEnforced(p *Pack) {
	leadText := "Controls the catalog lists for the resource types of these modules that no module manifest lists, and the layer that owns each one."
	if p.Catalog.EmbeddedSubset {
		leadText += " The catalog is the embedded one, which holds the CIS v6.0 controls only, so this list is not complete."
	}
	lead := []run{muted(leadText)}
	if len(p.NotEnforced) == 0 {
		d.chapter("6", sectionTitles[5].title, lead, 8, false)
		d.noneLine()
		return
	}
	t := table{widths: []float64{0.34, 0.22, 0.12, 0.32}, head: headCells("Control", "Resource types", "Layer", "Reason")}
	for _, ne := range p.NotEnforced {
		reason := []run{txt(orNotSet(ne.Reason))}
		if ne.SupersededBy != "" {
			reason = append(reason, txt(" Replaced in this build by "), mon(ne.SupersededBy), txt("."))
		}
		t.rows = append(t.rows, []tcell{
			{pp(sizeTable, mon(ne.ID)), pp(sizeTable, muted(orNotSet(ne.Name)))},
			codeList(ne.ResourceTypes), {pp(sizeTable, strong(orNotSet(ne.Layer)))}, {pp(sizeTable, reason...)},
		})
	}
	d.chapter("6", sectionTitles[5].title, lead, d.tableStart(t), false)
	d.drawTable(t, 0)
}

func (d *pdfDoc) tests(p *Pack) {
	tt := p.Tests
	if !tt.Supplied {
		d.chapter("7", sectionTitles[6].title, inline("No tests supplied. Pass `--tests-json` to `ctfkit report` to include the results of `tofu test -json` or `terraform test -json`.", muted("")), 0, false)
		return
	}
	lead := append([]run{muted("Results read from ")}, mon(orNotSet(tt.File)), muted(" (sha256 "), mon(orNotSet(tt.SHA256)), muted("): "+testSummary(tt)+"."))
	if len(tt.Cases) == 0 {
		d.chapter("7", sectionTitles[6].title, lead, 0, false)
		return
	}
	t := table{widths: []float64{0.5, 0.3, 0.2}, head: headCells("Test", "Module", "Result")}
	for _, c := range tt.Cases {
		t.rows = append(t.rows, []tcell{{pp(sizeTable, mon(c.Name))}, {pp(sizeTable, mon(orNotSet(c.ModuleKey)))}, {pp(sizeTable, strong(orNotSet(c.Status)))}})
	}
	d.chapter("7", sectionTitles[6].title, lead, d.tableStart(t), false)
	d.drawTable(t, 0)
}

func (d *pdfDoc) register(p *Pack) {
	lead := []run{muted("Every clause cited in this pack, as the module manifests name it, and the clauses the catalog records no control applies to.")}
	d.chapter("A", sectionTitles[7].title, lead, 20, true)
	if len(p.Register) == 0 {
		d.noneLine()
		return
	}
	for _, rf := range p.Register {
		t := table{widths: []float64{0.16, 0.54, 0.3}, head: headCells("Clause", "Title", "Controls")}
		for _, c := range rf.Clauses {
			t.rows = append(t.rows, []tcell{{pp(sizeTable, mon(orNotSet(c.ID)))}, {pp(sizeTable, txt(orNotSet(c.Title)))}, codeList(c.Controls)})
		}
		head := pp(10.5, fwRun(rf.Framework, orNotSet(rf.Name), bold))
		keep := 8.0
		if len(t.rows) > 0 {
			keep = d.tableStart(t)
		}
		d.y += 5
		d.ensure(2.5 + d.paraHeight(head, contentW) + 1.5 + keep)
		d.hline(marginX, marginX+contentW, d.y, rule2, ink)
		d.y += 2.5
		d.flow(head, marginX, contentW, 1.5)
		if len(t.rows) == 0 {
			d.flow(pp(sizeBody, txt(none+".")), marginX, contentW, 0)
		} else {
			d.drawTable(t, 0)
		}

		na := table{widths: []float64{0.16, 0.84}, head: headCells("Clause", "Reason")}
		for _, c := range rf.NotApplicable {
			na.rows = append(na.rows, []tcell{{pp(sizeTable, mon(orNotSet(c.ID)))}, {pp(sizeTable, txt(orNotSet(c.Reason)))}})
		}
		label := pp(sizeBody, strong("Clauses with no applicable control"))
		d.y += 3
		if len(na.rows) == 0 {
			label.runs = append(label.runs, txt(": "+none+"."))
			d.flow(label, marginX, contentW, 0)
			continue
		}
		d.ensure(d.paraHeight(label, contentW) + 1.5 + d.tableStart(na))
		d.flow(label, marginX, contentW, 1.5)
		d.drawTable(na, 0)
	}
}

// codeList is a cell with one mono line per value, since ids such as
// control names break at underscores and would run into each other.
func codeList(list []string) tcell {
	if len(list) == 0 {
		return tcell{pp(sizeTable, muted(none))}
	}
	out := make(tcell, 0, len(list))
	for _, s := range list {
		out = append(out, pp(sizeTable, mon(s)))
	}
	return out
}
